package com.kalin.investment_tracker.migration;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.*;

/** Read-only comparison with a disposable reference database built by the shipped migrations. */
public final class SchemaVerifier {
    private SchemaVerifier() { }

    public static void verify(Connection existing, Connection reference) throws SQLException {
        if (!existing.getMetaData().getDatabaseProductName().equals("MySQL")
                || !reference.getMetaData().getDatabaseProductName().equals("MySQL")) {
            throw new IllegalArgumentException("Schema adoption requires MySQL databases");
        }
        existing.setReadOnly(true);
        reference.setReadOnly(true);
        Map<String, String> actual = schema(existing);
        Map<String, String> expected = schema(reference);
        List<String> differences = new ArrayList<>();
        expected.forEach((key, value) -> {
            if (!value.equals(actual.get(key))) differences.add(key);
        });
        actual.keySet().stream().filter(key -> !expected.containsKey(key))
                .filter(key -> key.startsWith("table:") || key.startsWith("column:"))
                .forEach(differences::add);
        if (!differences.isEmpty()) {
            throw new IllegalStateException("Schema differs from the migration reference: " + String.join(", ", differences));
        }
        for (String table : List.of("_user", "role", "token")) {
            try (var statement = existing.createStatement();
                 var result = statement.executeQuery("SELECT COUNT(*), MIN(next_val), (SELECT COALESCE(MAX(id),0) FROM `"
                         + table + "`) FROM `" + table + "_seq`")) {
                result.next();
                if (result.getLong(1) != 1 || result.getLong(2) <= result.getLong(3)) {
                    throw new IllegalStateException("Unsafe pooled ID generator state: " + table + "_seq");
                }
            }
        }
        try (var statement = existing.createStatement(); var result = statement.executeQuery(
                "SELECT COUNT(*) FROM market_price_write_lock WHERE source='CSGOTRADER_24H'")) {
            result.next();
            if (result.getInt(1) != 1) throw new IllegalStateException("Missing market price write lock seed");
        }
    }

    private static Map<String, String> schema(Connection connection) throws SQLException {
        Map<String, String> result = new TreeMap<>();
        String schema = connection.getCatalog();
        try (var statement = connection.prepareStatement("""
                SELECT TABLE_NAME, ENGINE FROM information_schema.TABLES
                 WHERE TABLE_SCHEMA=? AND TABLE_NAME <> 'flyway_schema_history'
                """)) {
            statement.setString(1, schema);
            try (var rows = statement.executeQuery()) {
                while (rows.next()) result.put("table:" + rows.getString(1), rows.getString(2));
            }
        }
        try (var statement = connection.prepareStatement("""
                SELECT TABLE_NAME,COLUMN_NAME,COLUMN_TYPE,IS_NULLABLE,EXTRA,COLLATION_NAME
                  FROM information_schema.COLUMNS
                 WHERE TABLE_SCHEMA=? AND TABLE_NAME <> 'flyway_schema_history'
                """)) {
            statement.setString(1, schema);
            try (var rows = statement.executeQuery()) {
                while (rows.next()) result.put("column:" + rows.getString(1) + "." + rows.getString(2),
                        normalizedType(rows.getString(3)) + ":" + rows.getString(4) + ":" + rows.getString(5)
                                + ":" + rows.getString(6));
            }
        }
        // Constraint names generated by Hibernate differ from the explicit migration names.
        try (var statement = connection.prepareStatement("""
                SELECT TABLE_NAME,NON_UNIQUE,INDEX_NAME,
                       GROUP_CONCAT(CONCAT(COLUMN_NAME,':',COALESCE(SUB_PART,'')) ORDER BY SEQ_IN_INDEX)
                  FROM information_schema.STATISTICS
                 WHERE TABLE_SCHEMA=? AND TABLE_NAME <> 'flyway_schema_history'
                 GROUP BY TABLE_NAME,NON_UNIQUE,INDEX_NAME
                """)) {
            statement.setString(1, schema);
            try (var rows = statement.executeQuery()) {
                while (rows.next()) result.put("index:" + rows.getString(1) + ":" + rows.getString(2)
                        + ":" + rows.getString(4), "PRIMARY".equals(rows.getString(3)) ? "primary" : "index");
            }
        }
        try (var statement = connection.prepareStatement("""
                SELECT k.TABLE_NAME,k.COLUMN_NAME,k.REFERENCED_TABLE_NAME,k.REFERENCED_COLUMN_NAME,
                       r.DELETE_RULE,r.UPDATE_RULE
                  FROM information_schema.KEY_COLUMN_USAGE k
                  JOIN information_schema.REFERENTIAL_CONSTRAINTS r
                    ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME
                   AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
                 WHERE k.CONSTRAINT_SCHEMA=? AND k.REFERENCED_TABLE_NAME IS NOT NULL
                """)) {
            statement.setString(1, schema);
            try (var rows = statement.executeQuery()) {
                while (rows.next()) result.put("fk:" + rows.getString(1) + "." + rows.getString(2),
                        rows.getString(3) + "." + rows.getString(4) + ":" + rows.getString(5) + ":" + rows.getString(6));
            }
        }
        return result;
    }

    private static String normalizedType(String type) {
        if (type.startsWith("enum(")) {
            var values = new ArrayList<>(Arrays.asList(type.substring(5, type.length() - 1).split(",")));
            Collections.sort(values);
            return "enum(" + String.join(",", values) + ")";
        }
        return type;
    }
}
